"""Experiment 14F: hidden-memory Markovization test.

A controlled latent process is generated by a finite bank of exponentially
decaying hidden states. The observed scalar output is a weighted mixture of
those states plus measurement noise. The output alone is generally
non-Markovian, while the latent modal state is Markov.

The experiment asks whether a causal MIN/SOE representation of the noisy
observation recovers predictive information that is absent from the current
observation alone, and how it compares with explicit finite history.

Source geometries reuse the 14C rate families:
    clustered, logspread, wide
Each source has 16 hidden exponential modes with uniform weights.

The oracle baseline uses the true hidden state and therefore provides a
reference for the achievable one-step linear prediction from the actual
Markov state. It is not an observable implementation.
"""
from __future__ import annotations

import csv
import json
import importlib.util
from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

C_PATH = ROOT / "experiments" / "14C_geometry_to_task.py"
spec = importlib.util.spec_from_file_location("experiment14c", C_PATH)
mod = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = mod
spec.loader.exec_module(mod)

SOURCE_GEOMETRIES = mod.GEOMETRIES
MIN_GEOMETRIES = mod.GEOMETRIES
SEEDS = mod.SEEDS
SNR_DB = mod.SNR_DB
PCA_DIMENSIONS = (1, 2, 4, 8, 16)
RIDGE_LAMBDAS = (0.0, 1e-8, 1e-6)
HISTORY_LENGTHS = (1, 4, 16, 64)
COND_THRESHOLD = 1e12
TASK_TOLERANCE = 1.10
NUM_TRAIN_SAMPLES = 8192
NUM_TEST_SAMPLES = 8192
WARMUP = 256
PROCESS_DIMS = 16


def stable_ridge_fit(X: np.ndarray, y: np.ndarray, lam: float):
    design = np.column_stack([np.ones(X.shape[0], dtype=complex), X])
    gram = design.conj().T @ design
    scale = max(float(np.trace(gram).real) / gram.shape[0], np.finfo(float).tiny)
    alpha = float(lam) * scale
    reg = np.eye(gram.shape[0], dtype=complex)
    reg[0, 0] = 0.0
    if lam == 0.0:
        return np.linalg.lstsq(design, y, rcond=None)[0], 0.0
    beta = np.linalg.solve(gram + alpha * reg, design.conj().T @ y)
    return beta, alpha


def predict(X: np.ndarray, beta: np.ndarray) -> np.ndarray:
    return np.column_stack([np.ones(X.shape[0], dtype=complex), X]) @ beta


def nmse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    return float(
        np.mean(np.abs(y_pred - y_true) ** 2)
        / max(np.mean(np.abs(y_true) ** 2), np.finfo(float).tiny)
    )


def conditioning(X: np.ndarray) -> dict:
    design = np.column_stack([np.ones(X.shape[0], dtype=complex), X])
    singular = np.linalg.svd(design, compute_uv=False)
    smax = float(singular[0])
    positive = singular[singular > smax * np.finfo(float).eps]
    smin = float(positive[-1]) if positive.size else 0.0
    cond = float(smax / smin) if smin > 0 else float("inf")
    rank = int(np.sum(singular > smax * np.finfo(float).eps))
    return {
        "readout_condition_number": cond,
        "readout_numerical_rank": rank,
        "readout_ill_conditioned": int(cond > COND_THRESHOLD),
    }


def uniform_weights() -> np.ndarray:
    return np.full(PROCESS_DIMS, 1.0 / PROCESS_DIMS)


def generate_hidden_process(
    geometry: str, n: int, seed: int
) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    gammas = mod.rate_pattern(geometry)
    dt = mod.DT
    decay = np.exp(-gammas * dt)
    innovation_scale = np.sqrt(np.maximum(1.0 - decay**2, 0.0))

    hidden = np.empty((n, PROCESS_DIMS), dtype=float)
    hidden[0] = rng.normal(size=PROCESS_DIMS)
    innovations = rng.normal(size=(n - 1, PROCESS_DIMS))
    for k in range(1, n):
        hidden[k] = decay * hidden[k - 1] + innovation_scale * innovations[k - 1]

    weights = uniform_weights()
    signal = hidden @ weights
    signal /= max(float(np.std(signal)), np.finfo(float).tiny)
    hidden /= max(float(np.std(hidden @ weights)), np.finfo(float).tiny)
    return signal, hidden


def add_observation_noise(
    clean: np.ndarray, snr_db: float, seed: int
) -> np.ndarray:
    rng = np.random.default_rng(seed)
    sigma = float(np.std(clean)) / (10.0 ** (snr_db / 20.0))
    return clean + sigma * rng.normal(size=clean.size)


def history_matrix(y: np.ndarray, history: int, start: int):
    """Rows contain [y_n, y_{n-1}, ..., y_{n-history+1}] causally."""
    if history < 1:
        raise ValueError("history must be positive")
    end = y.size - 1
    indices = np.arange(max(start, history - 1), end)
    X = np.column_stack([y[indices - j] for j in range(history)])
    targets = indices + 1
    return X, targets


def build_prediction_pairs(
    observed: np.ndarray, clean: np.ndarray, start: int
):
    centers = np.arange(start, observed.size - 1)
    return observed[centers], clean[centers + 1], centers


def run_case(source_geometry: str, min_geometry: str, snr_db: float, seed: int, include_shared_baselines: bool = True):
    clean_train, hidden_train = generate_hidden_process(
        source_geometry, NUM_TRAIN_SAMPLES, seed
    )
    clean_test, hidden_test = generate_hidden_process(
        source_geometry, NUM_TEST_SAMPLES, seed + 10_000
    )
    y_train = add_observation_noise(clean_train, snr_db, seed + 20_000)
    y_test = add_observation_noise(clean_test, snr_db, seed + 70_000)

    train_x, train_target, centers_train = build_prediction_pairs(
        y_train, clean_train, WARMUP
    )
    test_x, test_target, centers_test = build_prediction_pairs(
        y_test, clean_test, WARMUP
    )

    rows = []

    # Current observation baseline.
    raw_beta, raw_alpha = stable_ridge_fit(
        train_x[:, None], train_target, 1e-6
    )
    raw_nmse = nmse(test_target, predict(test_x[:, None], raw_beta))

    # Explicit finite-history baselines are shared across MIN geometries for
    # a fixed source/SNR/seed because they use the identical noisy observation.
    history_results = {}
    for history in HISTORY_LENGTHS:
        hx_train, tidx_train = history_matrix(y_train, history, WARMUP)
        hx_test, tidx_test = history_matrix(y_test, history, WARMUP)
        # Keep target alignment explicit and causal: y_n -> x_{n+1}.
        hy_train = clean_train[tidx_train]
        hy_test = clean_test[tidx_test]
        history_results[history] = {}
        for lam in RIDGE_LAMBDAS:
            beta, alpha = stable_ridge_fit(hx_train, hy_train, lam)
            value = nmse(hy_test, predict(hx_test, beta))
            history_results[history][lam] = value
            if include_shared_baselines:
                rows.append({
                    "experiment": "14F_hidden_memory_markovization",
                    "representation": "finite_history",
                    "source_geometry": source_geometry,
                    "min_geometry": "",
                    "snr_db": float(snr_db),
                    "seed": int(seed),
                    "retained_dimension": int(history),
                    "history_length": int(history),
                    "ridge_lambda": float(lam),
                    "ridge_alpha": float(alpha),
                    "heldout_next_state_nmse": value,
                    "current_observation_nmse": raw_nmse,
                    "nmse_delta_vs_current": value - raw_nmse,
                    "matched_geometry": 0,
                })

    # Oracle: true hidden Markov state at n predicts the clean output at n+1.
    oracle_input_train = hidden_train[centers_train]
    oracle_target_train = clean_train[centers_train + 1]
    oracle_input_test = hidden_test[centers_test]
    oracle_target_test = clean_test[centers_test + 1]
    oracle_beta, oracle_alpha = stable_ridge_fit(
        oracle_input_train, oracle_target_train, 1e-6
    )
    oracle_nmse = nmse(oracle_target_test, predict(oracle_input_test, oracle_beta))
    if include_shared_baselines:
        rows.append({
            "experiment": "14F_hidden_memory_markovization",
            "representation": "oracle_hidden_state",
            "source_geometry": source_geometry,
            "min_geometry": "",
            "snr_db": float(snr_db),
            "seed": int(seed),
            "retained_dimension": PROCESS_DIMS,
            "history_length": 0,
            "ridge_lambda": 1e-6,
            "ridge_alpha": oracle_alpha,
            "heldout_next_state_nmse": oracle_nmse,
            "current_observation_nmse": raw_nmse,
            "nmse_delta_vs_current": oracle_nmse - raw_nmse,
            "matched_geometry": 0,
        })

    kernel = mod.KERNELS[min_geometry]
    q_train_all = mod.exact_piecewise_linear_states(
        y_train, kernel["gammas"], kernel["coefficients"]
    )
    q_test_all = mod.exact_piecewise_linear_states(
        y_test, kernel["gammas"], kernel["coefficients"]
    )
    q_train = q_train_all[centers_train]
    q_test = q_test_all[centers_test]

    cond = conditioning(q_train)
    mean = np.mean(q_train, axis=0)
    _, singular, components = mod.complex_pca_fit(q_train)
    curves = {}

    for d in PCA_DIMENSIONS:
        X_train = (q_train - mean) @ components[:, :d]
        X_test = (q_test - mean) @ components[:, :d]
        for lam in RIDGE_LAMBDAS:
            beta, alpha = stable_ridge_fit(X_train, train_target, lam)
            value = nmse(test_target, predict(X_test, beta))
            curves[(d, lam)] = value
            rows.append({
                "experiment": "14F_hidden_memory_markovization",
                "representation": "full_state",
                "source_geometry": source_geometry,
                "min_geometry": min_geometry,
                "snr_db": float(snr_db),
                "seed": int(seed),
                "retained_dimension": int(d),
                "history_length": 0,
                "ridge_lambda": float(lam),
                "ridge_alpha": float(alpha),
                "heldout_next_state_nmse": value,
                "current_observation_nmse": raw_nmse,
                "oracle_hidden_state_nmse": oracle_nmse,
                "nmse_delta_vs_current": value - raw_nmse,
                "nmse_delta_vs_oracle": value - oracle_nmse,
                "pca_explained_energy": mod.pca_energy(singular, d),
                "matched_geometry": int(source_geometry == min_geometry),
                **cond,
                **mod.KERNEL_DESCRIPTORS[min_geometry],
            })

    reference = curves[(16, 1e-6)]
    threshold = TASK_TOLERANCE * reference
    d_task = next(
        (d for d in PCA_DIMENSIONS if curves[(d, 1e-6)] <= threshold),
        None,
    )

    scalar_results = {}
    z_train = q_train @ kernel["weights"]
    z_test = q_test @ kernel["weights"]
    for lam in RIDGE_LAMBDAS:
        beta, alpha = stable_ridge_fit(z_train[:, None], train_target, lam)
        value = nmse(test_target, predict(z_test[:, None], beta))
        scalar_results[lam] = value
        rows.append({
            "experiment": "14F_hidden_memory_markovization",
            "representation": "scalar_min",
            "source_geometry": source_geometry,
            "min_geometry": min_geometry,
            "snr_db": float(snr_db),
            "seed": int(seed),
            "retained_dimension": 1,
            "history_length": 0,
            "ridge_lambda": float(lam),
            "ridge_alpha": float(alpha),
            "heldout_next_state_nmse": value,
            "current_observation_nmse": raw_nmse,
            "oracle_hidden_state_nmse": oracle_nmse,
            "nmse_delta_vs_current": value - raw_nmse,
            "nmse_delta_vs_oracle": value - oracle_nmse,
            "d_task_10pct": d_task,
            "pca_explained_energy": float("nan"),
            "matched_geometry": int(source_geometry == min_geometry),
            **cond,
            **mod.KERNEL_DESCRIPTORS[min_geometry],
        })

    case = {
        "experiment": "14F_hidden_memory_markovization",
        "source_geometry": source_geometry,
        "min_geometry": min_geometry,
        "snr_db": float(snr_db),
        "seed": int(seed),
        "current_observation_nmse": raw_nmse,
        "oracle_hidden_state_nmse": oracle_nmse,
        "min_full_state_nmse": float(reference),
        "min_full_state_gain_vs_current": float(raw_nmse - reference),
        "min_gap_to_oracle": float(reference - oracle_nmse),
        "min_d_task_10pct": d_task,
        "best_history_nmse": float(
            min(history_results[h][lam] for h in HISTORY_LENGTHS for lam in RIDGE_LAMBDAS)
        ),
        "history_best_length": int(
            min(
                HISTORY_LENGTHS,
                key=lambda h: min(history_results[h][lam] for lam in RIDGE_LAMBDAS),
            )
        ),
        "matched_geometry": int(source_geometry == min_geometry),
    }
    return rows, case


def summarize(cases):
    grouped = {}
    for c in cases:
        grouped.setdefault((c["source_geometry"], c["min_geometry"], c["snr_db"]), []).append(c)
    out = []
    for key, bucket in sorted(grouped.items()):
        source, minimum, snr = key
        out.append({
            "source_geometry": source,
            "min_geometry": minimum,
            "snr_db": float(snr),
            "n": len(bucket),
            "mean_current_nmse": float(np.mean([c["current_observation_nmse"] for c in bucket])),
            "mean_oracle_nmse": float(np.mean([c["oracle_hidden_state_nmse"] for c in bucket])),
            "mean_min_full_state_nmse": float(np.mean([c["min_full_state_nmse"] for c in bucket])),
            "mean_min_gain_vs_current": float(np.mean([c["min_full_state_gain_vs_current"] for c in bucket])),
            "mean_min_gap_to_oracle": float(np.mean([c["min_gap_to_oracle"] for c in bucket])),
            "mean_min_d_task": float(np.mean([
                c["min_d_task_10pct"] for c in bucket if c["min_d_task_10pct"] is not None
            ])),
            "mean_best_history_nmse": float(np.mean([c["best_history_nmse"] for c in bucket])),
            "mean_best_history_length": float(np.mean([c["history_best_length"] for c in bucket])),
        })
    return out


def main():
    eq = mod.validate_repository_equivalence()
    all_rows, cases = [], []

    for seed in SEEDS:
        for source_geometry in SOURCE_GEOMETRIES:
            for snr_db in SNR_DB:
                for min_geometry in MIN_GEOMETRIES:
                    rows, case = run_case(
                        source_geometry, min_geometry, snr_db, seed,
                        include_shared_baselines=(min_geometry == MIN_GEOMETRIES[0]),
                    )
                    all_rows.extend(rows)
                    cases.append(case)

    expected_cases = (
        len(SEEDS) * len(SOURCE_GEOMETRIES) * len(SNR_DB) * len(MIN_GEOMETRIES)
    )
    expected_full = expected_cases * len(PCA_DIMENSIONS) * len(RIDGE_LAMBDAS)
    expected_scalar = expected_cases * len(RIDGE_LAMBDAS)
    shared_cases = len(SEEDS) * len(SOURCE_GEOMETRIES) * len(SNR_DB)
    expected_history = shared_cases * len(HISTORY_LENGTHS) * len(RIDGE_LAMBDAS)
    expected_oracle = shared_cases

    assert len(cases) == expected_cases
    assert sum(r["representation"] == "full_state" for r in all_rows) == expected_full
    assert sum(r["representation"] == "scalar_min" for r in all_rows) == expected_scalar
    assert sum(r["representation"] == "finite_history" for r in all_rows) == expected_history
    assert sum(r["representation"] == "oracle_hidden_state" for r in all_rows) == expected_oracle

    out = ROOT / "experiments" / "results"
    out.mkdir(parents=True, exist_ok=True)
    detail = out / "14F_hidden_memory_markovization_results.csv"
    cases_path = out / "14F_hidden_memory_markovization_cases.csv"
    summary_path = out / "14F_hidden_memory_markovization_summary.csv"
    metadata_path = out / "14F_hidden_memory_markovization_summary.json"

    # Mixed representation schema: explicit superset fieldnames.
    fieldnames = [
        "experiment", "representation", "source_geometry", "min_geometry",
        "snr_db", "seed", "retained_dimension", "history_length",
        "ridge_lambda", "ridge_alpha", "heldout_next_state_nmse",
        "current_observation_nmse", "oracle_hidden_state_nmse",
        "nmse_delta_vs_current", "nmse_delta_vs_oracle", "pca_explained_energy",
        "matched_geometry", "d_task_10pct",
        "readout_condition_number", "readout_numerical_rank",
        "readout_ill_conditioned", "dictionary_mode_count",
        "weight_entropy_nats", "gfe_entropy_effective_count", "gfe_d_eff",
        "gfe_m_scale_decades", "gfe_m_res_modes_per_decade",
        "gfe_m_cap_s", "kernel_t50_s", "kernel_t90_s",
    ]
    with detail.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(all_rows)

    case_fields = list(cases[0])
    with cases_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=case_fields)
        writer.writeheader()
        writer.writerows(cases)

    summary_rows = summarize(cases)
    with summary_path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(summary_rows[0]))
        writer.writeheader()
        writer.writerows(summary_rows)

    metadata = {
        "experiment": "14F_hidden_memory_markovization",
        "purpose": "Test whether a causal MIN/SOE representation exposes predictive information in a controlled non-Markovian observed process whose true hidden modal state is Markov.",
        "source_process": "x_n = uniform weighted sum of 16 independent exponentially correlated latent modes; each mode follows q_{j,n+1}=a_j q_{j,n}+sqrt(1-a_j^2) epsilon_{j,n+1}, a_j=exp(-gamma_j*DT).",
        "observation": "y_n = x_n + independent white measurement noise.",
        "prediction_target": "clean latent output x_{n+1}; the next innovation is irreducible, so the task measures predictive state information rather than exact future reconstruction.",
        "source_geometries": list(SOURCE_GEOMETRIES),
        "min_geometries": list(MIN_GEOMETRIES),
        "snr_db": list(SNR_DB),
        "seeds": list(SEEDS),
        "pca_dimensions": list(PCA_DIMENSIONS),
        "history_lengths": list(HISTORY_LENGTHS),
        "ridge_lambdas": list(RIDGE_LAMBDAS),
        "train_samples": NUM_TRAIN_SAMPLES,
        "test_samples": NUM_TEST_SAMPLES,
        "warmup": WARMUP,
        "cases": expected_cases,
        "full_state_rows": expected_full,
        "scalar_rows": expected_scalar,
        "finite_history_rows": expected_history,
        "oracle_rows": expected_oracle,
        "total_rows": len(all_rows),
        "oracle_definition": "linear readout from the true hidden modal state; it is an information-rich reference, not an observable baseline.",
        "matched_geometry_definition": "source and MIN rate geometries are identical.",
        "causality": "Every predictor row at n uses y samples through n only. The target is x at n+1.",
        "paired_control": "For a fixed source/SNR/seed, the exact same clean process and noisy observation are reused across all three MIN geometries.",
        "task_dimension": "smallest retained MIN PCA dimension whose held-out NMSE at lambda=1e-6 is within 10% of that MIN geometry's full 16-state NMSE.",
        "interpretation_boundary": [
            "This tests Markovization/predictive-state accessibility in a controlled latent-memory process, not a universal prediction benchmark.",
            "Improvement over the current-observation baseline indicates access to temporal information; it does not prove exact recovery of the hidden state.",
            "The finite-history baselines separate explicit history length from the learned/constructed MIN state representation.",
            "The oracle hidden-state baseline measures remaining predictive headroom and is not available to an observer."
        ],
        "repository_equivalence_relative_error": eq,
    }
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps(metadata, indent=2))
    print(f"rows={len(all_rows)} cases={len(cases)} full={expected_full} scalar={expected_scalar} history={expected_history} oracle={expected_oracle}")


if __name__ == "__main__":
    main()
